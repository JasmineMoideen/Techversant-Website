/**
 * Generates src/styles/preflight.css: Tailwind's preflight with every selector guarded by
 * `:where(:not(.wp-page *))`, so it keeps resetting the hand-built shell/home page but does not touch
 * WordPress-rendered content (which is authored against browser defaults + Bootstrap's reboot — see css-scope.ts).
 *   pnpm build:preflight
 */
import fs from 'node:fs';
import postcss from 'postcss';

const GUARD = ':where(:not(.wp-page *))';

function guard(selector: string): string {
  const at = selector.indexOf('::');
  const subject = at === -1 ? selector : selector.slice(0, at);
  const pseudo = at === -1 ? '' : selector.slice(at);
  return `${subject.trim() === '' ? '*' : subject}${GUARD}${pseudo}`;
}

const src = fs.readFileSync('node_modules/tailwindcss/preflight.css', 'utf8');
const root = postcss.parse(src);
root.walkRules((rule) => {
  rule.selectors = rule.selectors.map(guard);
});
fs.writeFileSync('src/styles/preflight.css', `/* generated by scripts/build/preflight.ts from tailwindcss/preflight.css — do not edit */\n${root.toString()}`);
console.log('wrote src/styles/preflight.css');
